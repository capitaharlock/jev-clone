"""Render every result file in bench/results into bench/RESULTS.md.

    python -m bench.report
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "bench" / "results"
CELLS = ["difficulty:extreme", "difficulty:constrained", "options:3",
         "options:4", "options:5", "units:salt_g", "units:sodium_mg",
         "lang:en", "lang:es"]


def pct(value: float | None) -> str:
    return "" if value is None else f"{100 * value:.1f}"


def label(result: dict) -> str:
    system = result["system"]
    name = system["name"]
    if system["kind"] == "own":
        return f"{name} ({system['device']})"
    if system["kind"] == "ollama-chat":
        return f"{name}, zero-shot"
    return name


def render(results: list[dict]) -> str:
    results.sort(key=lambda r: -r["accuracy"])
    lines = [
        "# Benchmark results",
        "",
        "Generated by `python -m bench.report` from `bench/results/*.json`.",
        "Forced accuracy on `benchmark/product_specs.dev.jsonl`; rows marks a",
        "stratified subset when it is below 3000. Latency is per decision, one",
        "request at a time, on the host named in each result file.",
        "",
        "| System | Rows | Accuracy % | Wilson low % | Decidable % | p50 ms | p95 ms |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for r in results:
        lines.append(
            f"| {label(r)} | {r['rows']} | {pct(r['accuracy'])} | "
            f"{pct(r['wilson_lower'])} | {pct(r['decidable_accuracy'])} | "
            f"{r['latency_ms']['p50']:.1f} | {r['latency_ms']['p95']:.1f} |")
    lines += ["", f"Chance (uniform pick): {pct(results[0]['chance'])}%.", "",
              "## By question shape", "",
              "| System | " + " | ".join(c.split(":")[1] for c in CELLS) + " |",
              "|---|" + "---:|" * len(CELLS)]
    for r in results:
        lines.append(f"| {label(r)} | " + " | ".join(
            pct(r["by"].get(c, {}).get("accuracy")) for c in CELLS) + " |")
    return "\n".join(lines) + "\n"


def main() -> int:
    results = [json.loads(p.read_text(encoding="utf-8"))
               for p in sorted(RESULTS.glob("*.json"))]
    (ROOT / "bench" / "RESULTS.md").write_text(render(results),
                                               encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
